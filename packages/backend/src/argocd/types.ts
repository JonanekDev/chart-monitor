import type { OpenRepo } from '../git/repoSnapshot.js';

export interface HelmParameter {
  name: string;
  value: string;
}

export interface ApplicationSource {
  repoURL: string;
  chart?: string;
  targetRevision?: string;
  path?: string;
  /** Names this source so sibling sources can read files from it as `$<ref>/path` */
  ref?: string;
  helm?: {
    parameters?: HelmParameter[];
    values?: string;
    valuesObject?: Record<string, unknown>;
    valueFiles?: string[];
    ignoreMissingValueFiles?: boolean;
    apiVersions?: string[];
    kubeVersion?: string;
  };
}

export interface GitDirectoryGenerator {
  path: string;
  exclude?: boolean;
}

export interface GitFileGenerator {
  path: string;
}

export interface ApplicationSetGenerator {
  list?: {
    elements?: Record<string, unknown>[];
    values?: Record<string, unknown>;
  };
  git?: {
    repoURL: string;
    revision: string;
    directories?: GitDirectoryGenerator[];
    files?: GitFileGenerator[];
    values?: Record<string, unknown>;
  };
  /** Cartesian product of exactly two child generators */
  matrix?: {
    generators: ApplicationSetGenerator[];
  };
  /** First child is the base; later children override base rows that match on `mergeKeys` */
  merge?: {
    generators: ApplicationSetGenerator[];
    mergeKeys: string[];
  };
}

export interface ApplicationSetManifest {
  apiVersion: string;
  kind: 'ApplicationSet';
  metadata: { name: string };
  spec: {
    generators?: ApplicationSetGenerator[];
    template: {
      metadata?: { name?: string };
      spec?: {
        source?: ApplicationSource;
        sources?: ApplicationSource[];
      };
    };
  };
}

export interface ApplicationManifest {
  apiVersion: string;
  kind: 'Application';
  metadata: { name: string };
  spec: {
    source?: ApplicationSource;
    sources?: ApplicationSource[];
  };
}

export function isApplicationManifest(doc: unknown): doc is ApplicationManifest {
  return (
    typeof doc === 'object' &&
    doc !== null &&
    (doc as Record<string, unknown>).kind === 'Application' &&
    typeof (doc as Record<string, unknown>).spec === 'object'
  );
}

export function isApplicationSetManifest(doc: unknown): doc is ApplicationSetManifest {
  return (
    typeof doc === 'object' &&
    doc !== null &&
    (doc as Record<string, unknown>).kind === 'ApplicationSet' &&
    typeof (doc as Record<string, unknown>).spec === 'object'
  );
}

export interface ResolvedApplication {
  /** Empty for a plain `Application` that is not generated by an ApplicationSet. */
  applicationSetName: string;
  applicationName: string;
  sources: ApplicationSource[];
}

/** What scan steps need from the outside: repo access, and a sink for anything skipped or
 * unsupported, so it is reported to the user instead of silently producing fewer findings. */
export interface ScanContext {
  openRepo: OpenRepo;
  warn: (message: string) => void;
}

export function withWarningPrefix(ctx: ScanContext, prefix: string): ScanContext {
  return { ...ctx, warn: (message) => ctx.warn(`${prefix}: ${message}`) };
}
